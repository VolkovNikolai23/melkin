// В русской раскладке на месте знаков разметки стоят буквы: «>» — «Ю», «<» — «Б»,
// «{» — «Х», «}» — «Ъ», «:» (Shift+;) — «Ж», «;» — «ж». Если человек забыл переключить
// раскладку, превращаем такие сочетания в знаки. Разделители заменяем, только когда они
// стоят отдельным словом, — в обычных словах таких сочетаний не бывает.

const SEPARATORS: [string, string][] = [
  ['ЮЮЮ', '>>>'],
  ['ЮЮ1.', '>>1.'],
  ['ЮЮФ)', '>>A)'],
  ['ЮЮ', '>>'],
  ['ББ', '<<'],
  ['БЮ', '<>'],
  ['ЖЖ', '::'],
  ['жж', ';;'],
];

const esc = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const SEP_RE = new RegExp(`(^|\\s)(${SEPARATORS.map(([k]) => esc(k)).join('|')})(?=\\s|$)`, 'g');
const MAP = new Map(SEPARATORS);

/** Исправляет набор разметки в русской раскладке. Длина текста не меняется — курсор остаётся на месте. */
export function fixRussianLayout(text: string): string {
  if (!/[ЮБЖжХЪ]/.test(text)) return text;
  return (
    text
      .replace(SEP_RE, (_m, pre: string, sep: string) => pre + MAP.get(sep)!)
      // группа клоза: «ХХс1ЖЖ» → «{{c1::» (русская «с» на месте латинской c)
      .replace(/ХХ[сc](\d+)ЖЖ/g, '{{c$1::')
      .replace(/(\{\{c\d+::[^\n]*?)ЪЪ/g, '$1}}')
      .replace(/ХХ([^\n]+?)ЪЪ/g, '{{$1}}')
  );
}
